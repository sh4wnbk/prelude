r"""The agent instructions, held to the two rules that make them worth pasting.

`docs/orchestrate_agent.md` carries one fenced block, and that block is what
Shawn pastes into the agent in watsonx Orchestrate. The agent is created in
Orchestrate's UI and its model is fixed by the lab admins, so this file is the
only part of it this repo can hold.

Two rules are the reason the file exists.

**The verbatim rule.** The agent quotes the narration the buildup tool
returned, word for word, and does not paraphrase, shorten or add to it. A
rewritten sentence is new narration that nothing has checked.

**The label rule.** "Verified from play data" is a field of the buildup
response and never a phrase of the agent's, in any case, shortened, softened,
bracketed or placed after a name. `CLAUDE.md` allows no partial credit and no
softened variant, so an agent that could keep the phrase over its own
retelling would be the one way this repo's central claim could be broken by a
machine nobody here wrote. Rule 4 answers the other half of it: there is no
summarised narration to label, because the agent never writes one.

**The shape rule.** The whole answer to a request for the narration is the
narration text, and nothing else. It is Shawn's decision of 2026-11-07, taken
after the live agent quoted the 2022 narration word for word and then added a
line of its own: an em dash, the narrator's name, and the label behind it in
parentheses with its first letter lower-cased. The quoting was right and the
line after it broke three rules at once. So there is no shape for the extra
material, because there is none of it, which is what `TestTheAnswerIsTheNarration`
holds.

The label is read from `app/grounding.py` rather than spelled here, which is
the same thing `tests/test_api.py` does for the endpoint.

**The matches it serves.** Not a rule about the words, but the reason the
first live test of the agent went wrong in its second way: asked about a match,
it asked the fan for a StatsBomb match id, because nothing in its context said
which matches exist. The block carries the matches now, generated by
`scripts/write_served_matches.py`, and `TestTheMatchesItServes` below holds
what is in the file to the two sources that list is built from.

What the agent does with the words is not checkable from the repo. Step 5 of
the setup list in the doc is how that is checked, by asking it.
"""

import json
import re
from pathlib import Path

import pytest

from app.api import MATCHES, app
from app.grounding import GROUNDING_LABEL
from scripts.write_served_matches import ANCHOR, current, rows

ROOT = Path(__file__).resolve().parent.parent
DOC = ROOT / "docs" / "orchestrate_agent.md"
MATCHES_FILE = ROOT / "app" / "web" / "matches.json"
NARRATIONS_FILE = ROOT / "app" / "web" / "narrations.json"
RAW_MATCHES = ROOT / "data" / "raw" / "matches"

FENCE = re.compile(r"^```[a-z]*\n(.*?)^```", re.M | re.S)

#: Nicknames the app's copy already refuses, from the "verdict nickname" rows
#: of `BANNED` in `scripts/scan_copy.py`. The instructions are not screen copy,
#: so that gate does not read them, and a nickname in the words that teach an
#: agent what to say would travel further than one on a screen.
VERDICT_NICKNAMES = ("goal of the century", "hand of god", "controvers")

#: A command-line flag, in backticks. `CLAUDE.md` bans two hyphens standing in
#: for a dash and allows them inside a flag, and the rest of the docs register
#: names flags that way, so these come out of the text before the stand-in
#: check below reads it.
FLAG_IN_BACKTICKS = re.compile(r"`-{2}[a-z][a-z-]*`")


def doc_text() -> str:
    if not DOC.is_file():
        pytest.fail(f"{DOC.relative_to(ROOT).as_posix()} does not exist")
    return DOC.read_text(encoding="utf-8")


def instructions() -> str:
    """The one fenced block: the words that go into Orchestrate."""
    blocks = FENCE.findall(doc_text())
    assert len(blocks) == 1, f"expected one fenced block, found {len(blocks)}"
    return blocks[0]


def flat() -> str:
    """The block as one lower-case line.

    Every phrase below is checked against this rather than against the raw
    text, because where a sentence wraps is a matter of the margin and a
    rewrap is not a change to the rule.
    """
    return " ".join(instructions().split()).lower()


class TestTheBlockToPaste:
    def test_the_doc_is_in_the_repo(self):
        assert DOC.is_file()

    def test_there_is_exactly_one_block_to_paste(self):
        """Two blocks is an agent half configured, because only one of them
        gets pasted."""
        assert len(FENCE.findall(doc_text())) == 1

    def test_the_block_is_the_whole_brief_and_not_a_fragment(self):
        assert len(instructions().split()) >= 250

    def test_it_names_both_tools(self):
        block = flat()
        assert "moments tool" in block
        assert "buildup tool" in block


class TestTheVerbatimRule:
    def test_it_says_to_quote_word_for_word(self):
        block = flat()
        assert "word for word" in block
        assert "exactly as the buildup tool returned it" in block

    def test_it_forbids_paraphrasing_shortening_and_adding(self):
        block = flat()
        assert "never paraphrase" in block
        assert "never shorten" in block
        assert "never add" in block

    def test_the_verbatim_rule_is_the_first_rule(self):
        """The rules are ordered, and the one the label rests on is first.
        Written as `1.` in the block, so this reads the numbered list."""
        numbered = re.findall(r"^\s*(\d)\.\s+(.*)$", instructions(), re.M)
        assert numbered, "the block has no numbered rules"
        first = next(body for number, body in numbered if number == "1")
        assert "give the narration exactly as the buildup tool" in first.lower()


class TestTheLabelRule:
    def test_it_spells_the_label_the_way_the_check_does(self):
        """Read from `app/grounding.py`, so a change to the phrase fails here
        rather than leaving an agent quoting the old one."""
        assert GROUNDING_LABEL in instructions()

    def test_the_label_is_shown_only_when_the_response_carries_it(self):
        block = flat()
        assert "label field" in block
        assert "nothing else" in block

    def test_there_is_no_summarised_narration_at_all(self):
        """Rule 4. It used to let the agent summarise as long as it said so
        and dropped the label, which was a second way to answer a narration
        question and so a second thing to get right. There is one way now, and
        the other is a refusal.
        """
        block = flat()
        assert "never summarise or shorten a narration" in block
        assert "say that you cannot, and give none of them" in block

    def test_the_summarising_clause_is_gone_from_the_rules(self):
        """Rule 4 carried the old permission and the label clause that went
        with it. Both are out, and rule 2 is where the label prohibition is
        written, so neither word may come back into the block without this
        failing.
        """
        block = flat()
        assert "summarising" not in block
        assert "do not show the label" not in block

    def test_there_is_no_softened_variant_of_the_label(self):
        """`CLAUDE.md`: no partial credit and no softened variant. An agent
        told only "do not paraphrase" would still invent "partly verified".
        Held against rule 2, which is where this moved when rule 4 lost its
        label clause.
        """
        block = flat()
        assert "not shortened, not softened" in block
        assert "never write that phrase yourself" in block


class TestTheAnswerIsTheNarration:
    """Rule 3, and the live answer that is the reason for it.

    The agent quoted the 2022 narration word for word and then added a line of
    its own: an em dash, the narrator's name, and the label behind it in
    parentheses, lower-cased. `CLAUDE.md` allows the phrase only as
    `app/grounding.py` writes it and allows no em dash in any copy, so that one
    line was three breaches.

    Shawn's decision was not to give the extra material a shape. The answer is
    the `text` field and nothing else, so each test here is either the rule
    itself or one of the things the live answer added.
    """

    def test_the_answer_is_the_text_field_and_nothing_else(self):
        block = flat()
        assert "your whole answer is the text field" in block
        assert "exactly as returned, and nothing else" in block

    def test_nothing_comes_before_the_narration(self):
        block = flat()
        assert "nothing before it" in block
        assert "no preamble" in block

    def test_nothing_comes_after_the_narration(self):
        """Each thing the live answer added, named, so that none of them is
        left to the agent's own judgement."""
        block = flat()
        assert "nothing after it" in block
        for banned in (
            "no signature",
            "no byline",
            "no narrator's name",
            "no label",
            "no link",
            "no authorship line",
        ):
            assert banned in block, banned

    def test_no_dash_of_any_kind_goes_in_the_answer(self):
        """The live line opened with an em dash, and `CLAUDE.md` takes none in
        any copy. Said as every dash rather than as that one, because an en
        dash or a hyphen in its place would read the same way."""
        assert "no dash of any kind anywhere in the answer" in flat()

    def test_the_label_is_never_the_agents_to_write(self):
        block = flat()
        assert "not yours to write" in block
        assert "never write that phrase yourself" in block

    def test_the_label_in_the_block_is_the_checks_own_spelling(self):
        """Read from `app/grounding.py`, and every occurrence of it in the
        block has to be that exact spelling. The live answer lower-cased the
        first letter, and `CLAUDE.md` allows no softened variant, so a block
        that spelled it loosely anywhere would be teaching the thing that went
        wrong."""
        found = re.findall(re.escape(GROUNDING_LABEL), instructions(), re.I)
        assert found, "the block does not carry the label at all"
        assert set(found) == {GROUNDING_LABEL}

    def test_the_narrator_and_the_recording_stay_out_of_the_answer(self):
        """They are fields of the response, and rule 11 keeps them out rather
        than placing them somewhere."""
        block = flat()
        assert "audio_url" in block
        assert "not part of the answer" in block

    def test_the_block_carries_no_em_dash(self):
        """Scoped to the pasteable block. The whole file is held to the same
        rule by `test_it_carries_no_em_dash_and_no_stand_in_for_one`, and this
        one says it of the words the agent is actually given."""
        assert "—" not in instructions()

    def test_the_answer_is_the_whole_field(self):
        """The 1986 neutral answer of 2026-11-07 was the right narration with
        13 of its 65 words missing, the goal among them."""
        block = flat()
        assert "all of it." in block
        assert "from its first word to its last full stop" in block

    def test_it_refuses_a_cut_and_an_ellipsis(self):
        """The live answer stopped part way through a sentence and closed with
        an ellipsis. Rule 1 already forbade shortening; this says it in the
        terms the failure took."""
        block = flat()
        assert "never shorten it, never stop part way through" in block
        assert "never close it with an ellipsis" in block

    def test_the_fields_last_sentence_is_not_a_closing_sentence_of_the_agents(
        self,
    ):
        """The list of what may not follow the narration says "no closing
        sentence", and the 1986 narration ends "What a moment.", which is
        exactly the kind of sentence that list looks like it forbids. So the
        list says whose, and the rule says the field's own last sentence is
        the field's.
        """
        block = flat()
        assert "final sentence is part of the field" in block
        assert "no closing sentence of your own" in block

    def test_no_line_break_is_added(self):
        """The live answer broke one sentence across two lines."""
        block = flat()
        assert "one run of text." in block
        assert "the field arrives as one unbroken run" in block
        assert "do not break a sentence across two lines" in block

    def test_the_frozen_narrations_hold_no_line_break_and_no_ellipsis(self):
        """The premise the rule rests on, read off the file rather than
        asserted in the block. Every break and every ellipsis in an answer is
        the agent's, because there is none in what the service returns, and a
        frozen narration that grew one would make the rule wrong rather than
        the agent.
        """
        with NARRATIONS_FILE.open(encoding="utf-8") as handle:
            narrations = json.load(handle)["narrations"]
        slots = [
            (match, slot, record["text"])
            for match, entry in narrations.items()
            for slot, record in entry["slots"].items()
        ]
        assert slots, "no frozen narrations to read"
        for match, slot, text in slots:
            where = f"{match} {slot}"
            assert text == " ".join(text.split()), where
            assert "..." not in text, where
            assert "…" not in text, where

    def test_no_shape_for_the_extra_material_is_left_in_the_block(self):
        """A leftover label line or audio line would be a second and softer
        instruction standing beside rule 3."""
        block = instructions()
        assert "Listen:" not in block
        assert "·" not in block


class TestTheMatchesItServes:
    """The list of matches in the block, held to what it is built from.

    `scripts/write_served_matches.py` builds it, and its docstring says why
    each half comes from where it does: the id and the team names from
    `app/web/matches.json`, which is the service's own list of what it serves,
    and the competition, the season, the stage and the date from the StatsBomb
    match files under `data/raw/matches/`, because `app/web/matches.json`
    records neither a competition nor a stage.
    """

    def test_the_list_is_in_the_block_the_agent_is_given(self):
        """Not in the prose around it. The ids are no use to the agent unless
        they are in the words it is pasted."""
        block = instructions()
        assert ANCHOR in block
        for line in current(doc_text()):
            assert line in block, line

    def test_the_list_is_what_the_writer_builds(self):
        """`scripts/write_served_matches.py --check` is this check at the
        command line. Here it fails the suite, so a match added to the app
        cannot reach a judge with the agent still listing the old two."""
        assert current(doc_text()) == rows()

    def test_there_is_one_line_per_match_the_service_serves(self):
        assert len(current(doc_text())) == len(MATCHES)

    def test_every_line_is_a_match_id_matches_json_serves(self):
        """The ids, read from `app/web/matches.json` in its own order. The
        service answers for exactly these, which is `MATCHES` in
        `app/api.py`."""
        with MATCHES_FILE.open(encoding="utf-8") as handle:
            served = [e["match_id"] for e in json.load(handle)["matches"]]
        listed = [int(line[2:].split(":", 1)[0]) for line in current(doc_text())]
        assert listed == served
        assert set(listed) == set(MATCHES)

    def test_every_line_names_the_two_teams_matches_json_names(self):
        with MATCHES_FILE.open(encoding="utf-8") as handle:
            served = json.load(handle)["matches"]
        for entry, line in zip(served, current(doc_text()), strict=True):
            assert f"{entry['home_team']} vs {entry['away_team']}" in line

    def test_the_competition_and_the_stage_are_the_play_datas_own(self):
        """`app/web/matches.json` holds neither, so these are read off the
        match files `scripts/fetch_statsbomb.py` downloads. Nothing about the
        competition or the round is typed into this repo."""
        if not RAW_MATCHES.is_dir():
            pytest.fail(
                f"{RAW_MATCHES.relative_to(ROOT).as_posix()} is not there. "
                "Run scripts/fetch_statsbomb.py; data/raw is gitignored and "
                "reproducible, which is what the fixture in "
                "tests/test_event_feed.py says for the same reason."
            )
        raw = {}
        for path in sorted(RAW_MATCHES.glob("*/*.json")):
            with path.open(encoding="utf-8") as handle:
                for record in json.load(handle):
                    raw[record["match_id"]] = record
        for line in current(doc_text()):
            record = raw[int(line[2:].split(":", 1)[0])]
            assert record["competition"]["competition_name"] in line
            assert record["season"]["season_name"] in line
            assert record["competition_stage"]["name"] in line
            assert record["match_date"] in line

    def test_it_is_told_to_choose_the_match_itself(self):
        block = flat()
        assert "choose the match yourself" in block
        assert "from the list above" in block

    def test_it_is_told_never_to_ask_a_fan_for_a_match_id(self):
        """The one thing the first live test of the agent actually did."""
        assert "never ask a fan for a statsbomb match id" in flat()

    def test_it_is_told_to_pass_the_id_as_digits(self):
        """The other half of the live failure. Orchestrate serialises an
        integer tool argument as a float, so `match` is a string of digits and
        the agent is told to send it as one."""
        assert "written as digits" in flat()


class TestWhatItAsksAndWhatItWillNotSay:
    def test_it_asks_who_the_fan_is_with(self):
        assert "who are you with?" in flat()
        assert "ask once" in flat()

    def test_the_three_answers_are_the_ones_the_api_takes(self):
        """From the `Literal` in `app/api.py`, through `app.openapi()`, so an
        agent is never taught a fourth answer or a renamed one."""
        enum = next(
            parameter["schema"]["enum"]
            for parameter in app.openapi()["paths"]["/buildup"]["get"]["parameters"]
            if parameter["name"] == "listener"
        )
        block = instructions()
        for value in enum:
            assert value in block, value

    def test_it_forbids_verdict_nicknames(self):
        block = flat()
        assert "nickname" in block
        assert "do not use a nickname" in block

    def test_the_file_uses_no_verdict_nickname_itself(self):
        """Including in the explanation around the block. Naming the nickname
        in order to forbid it would put it in the agent's context, which is
        the one place it must not be."""
        text = doc_text().lower()
        for nickname in VERDICT_NICKNAMES:
            assert nickname not in text, nickname

    def test_it_carries_no_em_dash_and_no_stand_in_for_one(self):
        """`CLAUDE.md`'s rule, and this file is doc copy and pasted copy at
        once. `scripts/check_docs.py` reads the em dash across the docs
        register; the two-hyphen stand-in is checked here.

        A backticked flag is taken out first. `CLAUDE.md` allows two hyphens
        inside a command-line flag and nowhere else, and this file names one,
        so checking the raw text would ban what the rule permits.
        """
        text = doc_text()
        assert "—" not in text
        assert "--" not in FLAG_IN_BACKTICKS.sub("", text)
