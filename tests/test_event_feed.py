"""Acceptance tests the EventFeed module must pass.

These are written against the contract in `app/event_feed.py`. Nothing
implements it yet, so every test here fails on the `feed` fixture with a
message saying exactly that. They start passing when Bob ships
`app/statsbomb_event_feed.py`.

Two matches are covered:

  * 1986 Argentina vs England (3750191). Expected values are the ones
    `scripts/data_check.py` produced and `docs/data_check.md` records. They are
    written out literally here, on purpose, so a regression in the feed shows up
    as a disagreement with a report that was generated independently.

  * 2022 Argentina vs France (3869685). Expected values are read out of the raw
    JSON at test time rather than written down, and cross-checked against the
    score in the match index, which is a separate file. Nothing about this match
    is recalled.
"""

import json
from pathlib import Path

import pytest

from app.event_feed import EventFeed, EventWindow

ROOT = Path(__file__).resolve().parent.parent
RAW = ROOT / "data" / "raw"

MATCH_1986 = 3750191
MATCH_2022 = 3869685

EVENTS_1986 = RAW / "events" / f"{MATCH_1986}.json"
EVENTS_2022 = RAW / "events" / f"{MATCH_2022}.json"
MATCHES_1986 = RAW / "matches" / "43" / "54.json"
MATCHES_2022 = RAW / "matches" / "43" / "106.json"

# From docs/data_check.md, generated by scripts/data_check.py.
# (team, player, minute, second), earliest first.
GOALS_1986 = [
    ("Argentina", "Diego Armando Maradona", 50, 27),
    ("Argentina", "Diego Armando Maradona", 54, 18),
    ("England", "Gary Lineker", 80, 37),
]

# Periods 1 to 4 are the match. Period 5 is the penalty shootout, which is not a
# defining moment of the match: the shootout decides the trophy, not the score.
LAST_MATCH_PERIOD = 4


# The module Bob builds. Named once so the checks and the messages below cannot
# drift apart.
IMPL_MODULE = "app.statsbomb_event_feed"


def make_feed() -> EventFeed:
    """The implementation under test.

    A plain helper rather than a fixture, so that while nothing is implemented
    the suite reports 14 failures rather than 14 fixture errors. It fails rather
    than skips: a skip would let the suite go green with nothing built.
    """
    try:
        from app.statsbomb_event_feed import StatsBombEventFeed
    except ModuleNotFoundError as exc:
        if exc.name != IMPL_MODULE:
            # The module exists but one of ITS imports is missing. That is a
            # broken implementation, not an absent one, so let it surface with
            # a real traceback rather than be reported as "not built yet".
            raise
        pytest.fail(
            f"No EventFeed implementation yet: {IMPL_MODULE} does not exist. "
            "This is the expected failure until Bob builds the module; "
            "see docs/bob_brief.md."
        )
    except ImportError as exc:
        pytest.fail(
            f"{IMPL_MODULE} exists but does not provide StatsBombEventFeed "
            f"({exc})."
        )
    return StatsBombEventFeed()


@pytest.fixture(scope="session", autouse=True)
def raw_data_present():
    """Fail loudly if the gitignored raw data is missing, so it is never
    mistaken for a failure of the module."""
    missing = [p for p in (EVENTS_1986, EVENTS_2022, MATCHES_1986, MATCHES_2022) if not p.exists()]
    if missing:
        pytest.fail(
            "Missing raw data: "
            + ", ".join(str(p.relative_to(ROOT)) for p in missing)
            + ". Run scripts/fetch_statsbomb.py."
        )


def read_json(path: Path):
    with path.open(encoding="utf-8") as handle:
        return json.load(handle)


def goal_tuples(events, *, periods) -> list[tuple[str, str, int, int]]:
    """(team, player, minute, second) for every Goal-outcome shot in `periods`."""
    goals = [
        event
        for event in events
        if event["type"]["name"] == "Shot"
        and event["shot"]["outcome"]["name"] == "Goal"
        and event["period"] in periods
    ]
    goals.sort(key=lambda e: (e["period"], e["minute"], e["second"]))
    return [
        (e["team"]["name"], e["player"]["name"], e["minute"], e["second"]) for e in goals
    ]


def moment_tuples(moments) -> list[tuple[str, str, int, int]]:
    return [(m.team, m.player, m.minute, m.second) for m in moments]


def aggregate_score(matches_path: Path, match_id: int) -> int:
    entry = next(m for m in read_json(matches_path) if m["match_id"] == match_id)
    return entry["home_score"] + entry["away_score"]


class TestContract:
    def test_satisfies_the_event_feed_protocol(self):
        feed = make_feed()
        assert isinstance(feed, EventFeed)

    def test_load_match_returns_the_whole_feed(self):
        feed = make_feed()
        events = feed.load_match(MATCH_1986)
        assert len(events) == len(read_json(EVENTS_1986))


class Test1986:
    """Argentina vs England, 1986-06-22. Values from docs/data_check.md."""

    def test_finds_exactly_three_goals(self):
        feed = make_feed()
        moments = feed.defining_moments(MATCH_1986)
        goals = [m for m in moments if m.type == "Goal"]
        assert len(goals) == 3

    def test_goals_match_the_data_check(self):
        feed = make_feed()
        goals = [m for m in feed.defining_moments(MATCH_1986) if m.type == "Goal"]
        assert moment_tuples(goals) == GOALS_1986

    def test_goal_count_reconciles_with_the_match_index(self):
        feed = make_feed()
        goals = [m for m in feed.defining_moments(MATCH_1986) if m.type == "Goal"]
        assert len(goals) == aggregate_score(MATCHES_1986, MATCH_1986) == 3

    def test_minutes_are_the_raw_floored_clock(self):
        """StatsBomb floors the clock. The first goal is minute 50, not 51."""
        feed = make_feed()
        goals = [m for m in feed.defining_moments(MATCH_1986) if m.type == "Goal"]
        assert (goals[0].minute, goals[0].second) == (50, 27)

    def test_moments_are_ordered_earliest_first(self):
        feed = make_feed()
        moments = feed.defining_moments(MATCH_1986)
        clocks = [(m.minute, m.second) for m in moments]
        assert clocks == sorted(clocks)


class Test2022:
    """Argentina vs France, 2022-12-18. Expectations read from the data."""

    def test_goals_match_the_raw_feed(self):
        feed = make_feed()
        expected = goal_tuples(
            read_json(EVENTS_2022), periods=range(1, LAST_MATCH_PERIOD + 1)
        )
        goals = [m for m in feed.defining_moments(MATCH_2022) if m.type == "Goal"]
        assert moment_tuples(goals) == expected

    def test_goal_count_reconciles_with_the_match_index(self):
        """The events feed and the match index are separate files; a correct
        implementation agrees with both."""
        feed = make_feed()
        goals = [m for m in feed.defining_moments(MATCH_2022) if m.type == "Goal"]
        assert len(goals) == aggregate_score(MATCHES_2022, MATCH_2022)

    def test_shootout_penalties_are_not_defining_moments(self):
        """Period 5 is the shootout. Its penalties are goals in the feed but not
        goals in the match, and must not appear."""
        feed = make_feed()
        shootout = set(goal_tuples(read_json(EVENTS_2022), periods={5}))
        assert shootout, "expected the 2022 final to contain a shootout"
        returned = set(moment_tuples(feed.defining_moments(MATCH_2022)))
        assert returned.isdisjoint(shootout)


class TestEventWindow:
    def test_window_ends_at_the_moment(self):
        feed = make_feed()
        moment = [m for m in feed.defining_moments(MATCH_1986) if m.type == "Goal"][1]
        window = feed.event_window(MATCH_1986, moment, seconds_before=30.0)
        assert isinstance(window, EventWindow)
        assert window.moment == moment
        last = window.events[-1]
        assert (last["minute"], last["second"]) == (moment.minute, moment.second)

    def test_window_is_in_feed_order_and_within_the_span(self):
        feed = make_feed()
        moment = [m for m in feed.defining_moments(MATCH_1986) if m.type == "Goal"][1]
        seconds_before = 30.0
        window = feed.event_window(MATCH_1986, moment, seconds_before=seconds_before)

        indexes = [e["index"] for e in window.events]
        assert indexes == sorted(indexes)

        end = moment.minute * 60 + moment.second
        start = end - seconds_before
        for event in window.events:
            at = event["minute"] * 60 + event["second"]
            assert start <= at <= end

    def test_window_reports_the_requested_span(self):
        feed = make_feed()
        moment = [m for m in feed.defining_moments(MATCH_1986) if m.type == "Goal"][1]
        window = feed.event_window(MATCH_1986, moment, seconds_before=30.0)
        assert window.seconds_before == 30.0

    def test_window_events_are_raw_source_records(self):
        """The window hands back untouched feed records, because
        "Verified from play data" has to point at something in data/raw/."""
        feed = make_feed()
        moment = [m for m in feed.defining_moments(MATCH_1986) if m.type == "Goal"][1]
        window = feed.event_window(MATCH_1986, moment, seconds_before=30.0)
        raw_by_id = {e["id"]: e for e in read_json(EVENTS_1986)}
        for event in window.events:
            assert event["id"] in raw_by_id
            assert event == raw_by_id[event["id"]]
