"""Sanity-check the 1986 Argentina vs England event feed and write docs/data_check.md.

Lists every Shot whose outcome is Goal, counts shots per team, and tests the
claim that Argentina took 13 of the match's 15 shots. Every number in the
report comes from the data; nothing is written by hand.
"""

import json
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
EVENTS = ROOT / "data" / "raw" / "events" / "3750191.json"
MATCHES = ROOT / "data" / "raw" / "matches" / "43" / "54.json"
REPORT = ROOT / "docs" / "data_check.md"

MATCH_ID = 3750191

# The claim under test, stated as data so the report can quote it either way.
CLAIM_ARGENTINA_SHOTS = 13
CLAIM_TOTAL_SHOTS = 15

MINUTE_NOTE = (
    "StatsBomb's `minute` field floors the match clock, so an event at "
    "`minute: 50, second: 27` sits in the 51st minute as a broadcast would "
    "caption it. The table above reports raw StatsBomb values; add one to read "
    "them as on-screen clock time."
)


def load(path):
    if not path.exists():
        raise SystemExit(f"missing {path}; run scripts/fetch_statsbomb.py first")
    with path.open(encoding="utf-8") as handle:
        return json.load(handle)


def match_label(matches):
    for entry in matches:
        if entry["match_id"] == MATCH_ID:
            return (
                f"{entry['home_team']['home_team_name']} "
                f"{entry['home_score']}-{entry['away_score']} "
                f"{entry['away_team']['away_team_name']}",
                entry["match_date"],
                entry["competition_stage"]["name"],
            )
    raise SystemExit(f"match {MATCH_ID} not found in {MATCHES}")


def main():
    events = load(EVENTS)
    scoreline, match_date, stage = match_label(load(MATCHES))

    shots = [e for e in events if e["type"]["name"] == "Shot"]
    goals = [s for s in shots if s["shot"]["outcome"]["name"] == "Goal"]
    goals.sort(key=lambda s: (s["period"], s["minute"], s["second"]))

    per_team = Counter(s["team"]["name"] for s in shots)
    total = len(shots)
    # Order teams by shot count, highest first, so the table leads with the claim's subject.
    ranked = per_team.most_common()

    lines = [
        "# Data check: 1986 Argentina vs England",
        "",
        f"Match `{MATCH_ID}`: {scoreline}, {stage}, {match_date}.",
        f"Source: `data/raw/events/{MATCH_ID}.json` ({len(events):,} events).",
        "Generated by `scripts/data_check.py`; re-run it to refresh.",
        "",
        "## Goals",
        "",
        "| # | Player | Team | Minute | Second | Period | Shot type |",
        "| - | ------ | ---- | -----: | -----: | -----: | --------- |",
    ]
    for n, shot in enumerate(goals, start=1):
        lines.append(
            f"| {n} | {shot['player']['name']} | {shot['team']['name']} | "
            f"{shot['minute']} | {shot['second']} | {shot['period']} | "
            f"{shot['shot']['type']['name']} |"
        )

    lines += [
        "",
        f"**Note on minutes.** {MINUTE_NOTE}",
        "",
        "## Shots per team",
        "",
        "| Team | Shots |",
        "| ---- | ----: |",
    ]
    for team, count in ranked:
        lines.append(f"| {team} | {count} |")
    lines.append(f"| **Total** | **{total}** |")

    # Test the claim: Argentina 13 of 15 shots.
    argentina = per_team.get("Argentina", 0)
    claim_holds = argentina == CLAIM_ARGENTINA_SHOTS and total == CLAIM_TOTAL_SHOTS
    lines += [
        "",
        "## Claim check",
        "",
        f"> Argentina took {CLAIM_ARGENTINA_SHOTS} of the match's {CLAIM_TOTAL_SHOTS} shots.",
        "",
    ]
    if claim_holds:
        lines.append(f"**Confirmed.** Argentina {argentina} of {total}.")
    else:
        other = ", ".join(f"{team} {count}" for team, count in ranked if team != "Argentina")
        lines += [
            f"**Not supported by the data.** The feed has {total} shots in total, "
            f"not {CLAIM_TOTAL_SHOTS}: Argentina {argentina}, {other}.",
            "",
            f"Both halves of the claim are off. Argentina's count is {argentina}, "
            f"not {CLAIM_ARGENTINA_SHOTS}, and the match total is {total}, not "
            f"{CLAIM_TOTAL_SHOTS}. Argentina's share is "
            f"{argentina}/{total} ({argentina / total:.1%}).",
        ]

    REPORT.parent.mkdir(parents=True, exist_ok=True)
    # newline="\n" keeps LF on Windows, matching .gitattributes so committing
    # the report does not trip git's CRLF normalization warning.
    REPORT.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")

    # Echo the same figures to stdout so the run itself is the evidence.
    print(f"events          {len(events):,}")
    print(f"shots total     {total}")
    for team, count in ranked:
        print(f"  {team:<12} {count}")
    print(f"goals           {len(goals)}")
    for shot in goals:
        print(
            f"  {shot['minute']:>3}:{shot['second']:02d}  p{shot['period']}  "
            f"{shot['team']['name']:<10} {shot['player']['name']} "
            f"({shot['shot']['type']['name']})"
        )
    print(f"claim 13-of-15  {'CONFIRMED' if claim_holds else 'REFUTED'}")
    print(f"wrote           {REPORT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
